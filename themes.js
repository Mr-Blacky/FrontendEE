export const THEME_IDS = Object.keys(THEMES);

export function gamePalette(themeId) {
  const t = THEMES[themeId] || THEMES.dark;
  const isBright = themeId === "light";
  return {
    bg: t.vars["--bg"],
    fg: t.vars["--teal"],
    accent: t.vars["--purple"],
    muted: t.vars["--card"],
    textOn: isBright ? "#fff" : "#000",
  };
}
